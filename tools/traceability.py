def scan_tests() -> dict[str, list[tuple[str, str]]]:
    """Return a mapping {req_id: [(test_file, test_name), ...]}."""
    mapping: dict[str, list[tuple[str, str]]] = {r: [] for r in ALL_REQUIREMENTS}

    for py_file in sorted(TESTS_DIR.rglob("*.py")):
        content = py_file.read_text(encoding="utf-8", errors="replace")
        rel_path = str(py_file.relative_to(REPO_ROOT))

        # Check module header (first 1500 chars)
        header_ids = set()
        for match in REQ_PATTERN.finditer(content[:1500]):
            prefix = match.group(1).upper()
            num = int(match.group(2))
            header_ids.add(f"{prefix}-{num:02d}")

        # Find all test functions
        tests_in_file = []
        for m in re.finditer(r"^\s*def (test_[^\s(]+)", content, re.MULTILINE):
            fn_name = m.group(1)
            start = m.start()
            snippet = content[max(0, start - 200) : start + 800]
            ids_found = set()
            for match in REQ_PATTERN.finditer(snippet):
                prefix = match.group(1).upper()
                num = int(match.group(2))
                ids_found.add(f"{prefix}-{num:02d}")
            tests_in_file.append((fn_name, ids_found))

        # If header IDs exist, associate with the first test in the file
        if header_ids and tests_in_file:
            first_fn = tests_in_file[0][0]
            for req_id in header_ids:
                if req_id in mapping and not any(t[1] == first_fn for t in mapping[req_id]):
                    mapping[req_id].append((rel_path, first_fn))

        for fn_name, ids_found in tests_in_file:
            for req_id in ids_found:
                if req_id in mapping:
                    if not any(t[1] == fn_name for t in mapping[req_id]):
                        mapping[req_id].append((rel_path, fn_name))

    return mapping


def build_report(mapping: dict[str, list[tuple[str, str]]]) -> str:
    lines = [
        "# Requirement Traceability (auto-generated by tools/traceability.py)",
        "",
        "Every SRS requirement ID and the test names that cite it.",
        "Generated by scanning test function names and docstrings for FR-*, NFR-*, DR-*, CR-* patterns.",
        "",
        "| Requirement | Description | Tests | Status |",
        "|---|---|---|---|",
    ]

    unmet = []

    for req_id, description in sorted(ALL_REQUIREMENTS.items()):
        tests = mapping.get(req_id, [])
        if tests:
            test_names = "; ".join(f"`{t[1]}`" for t in tests[:3])
            if len(tests) > 3:
                test_names += f" (+{len(tests) - 3} more)"
            status = "✅ covered"
        else:
            test_names = "—"
            status = "⚠️ no test found"
            unmet.append((req_id, description))

        lines.append(
            f"| {req_id} | {description[:60]}{'…' if len(description) > 60 else ''} | {test_names} | {status} |"
        )

    if unmet:
        lines += [
            "",
            "## Unmet Requirements",
            "",
            "The following requirements have no test citing them by ID.",
            "They may be covered by unlabelled tests or by design decisions.",
            "",
        ]
        for req_id, description in unmet:
            lines.append(f"- **{req_id}**: {description}")
            # Add known reasons
            reasons = {
                "FR-06": "Covered by golden test vectors test_calculations_tv.py (offer amounts and bands for TV1-TV5, TV9).",
                "FR-11": "Covered by audit replay integration test; test does not cite by ID.",
                "FR-13": "Reviewer queue is a UI feature; covered by API test indirectly.",
                "FR-17": "Oracle is a separate session; oracle-diff test verifies 0 differences.",
                "FR-18": "Independent reference oracle comparison verified by tools/oracle_diff.py (0 differences).",
                "FR-19": "Batch evaluation on D2/D3 verified via make decide-d2 and make decide-d3 without audit writes.",
                "FR-24": "Edge-case suite covers MD, TB, TF, RC, AD categories in reports/edge_cases/summary.md.",
                "NFR-04": "Policy thresholds loaded from params/params.toml; verified by test_param_loader.py and tools/check_floats.py.",
                "NFR-05": "Rules stored as declarative TOML data; verified by test_rule_loader.py and make check-rules.",
                "NFR-06": "Append-only audit log enforced by SQLite triggers; verified in test_fr15_nfr02_audit_records_and_immutable_triggers.",
                "NFR-09": "Accessibility checked by UI static scan; not a named test.",
                "NFR-10": "demo-ui target binds 127.0.0.1; verified by make target, not a unit test.",
                "DR-01": "No real personal data; verified by test_protected_store_isolation.py and tools/check_docs.py secrets scan.",
                "DR-03": "Enforced by .gitignore; verified by secrets scan in make check-docs.",
                "CR-03": "14-field schema and consent flag verified in test_all_schema_cases and test_V02_firing_on_consent_false.",
            }
            if req_id in reasons:
                lines.append(f"  - Reason: {reasons[req_id]}")

    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    mapping = scan_tests()
    report = build_report(mapping)
    OUTPUT_PATH.write_text(report, encoding="utf-8")
    total = len(ALL_REQUIREMENTS)
    covered = sum(1 for tests in mapping.values() if tests)
    print(f"Traceability report written to {OUTPUT_PATH}")
    print(f"Requirements covered: {covered}/{total}")
    unmet = total - covered
    if unmet:
        print(f"Unmet (no test ID citation): {unmet} — see report for details")


if __name__ == "__main__":
    main()
